const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const C=require('./dist/model.js');
assert.equal(C.kennels.length,150);
assert.equal(new Set(C.kennels).size,150);
for(const b of [1,2,3,4,6])assert.equal(C.kennelsFor(b).length,30);
assert.equal(C.kennelsFor(5).length,0);
assert.equal(C.age('2012-08-01','2026-10-12'),'14 ปี 2 เดือน 11 วัน');
assert.equal(C.age('2012-08-01','2026-07-31'),'13 ปี 11 เดือน 30 วัน');
assert.equal(C.age('2025-01-31','2025-03-01'),'0 ปี 1 เดือน 1 วัน');
assert.equal(C.age('2024-02-29','2025-02-28'),'1 ปี 0 เดือน 0 วัน');
const state=C.seed();
assert.throws(()=>C.validateAnimal({...state.animals[0]},state.animals),/มีอยู่แล้ว/);
assert.throws(()=>C.validateAnimal({...state.animals[0],id:'NEW',birth:'2999-01-01'},state.animals),/อนาคต/);
const sunny=state.animals[0];sunny.notes.push({text:'retain'});
assert.equal(C.moveAnimal(sunny,'D1-B15'),'D1-A01');
assert.equal(sunny.kennel,'D1-B15');assert.equal(sunny.notes[0].text,'retain');
assert.throws(()=>C.moveAnimal(sunny,'D1-B15'),/อยู่ในคอกนี้แล้ว/);
assert.equal(C.moveAnimal(sunny,'D2-A01'),'D1-B15');
assert.equal(C.moveAnimal(sunny,'D6-B15'),'D2-A01');
assert.equal(sunny.notes[0].text,'retain');
assert.throws(()=>C.moveAnimal(sunny,'D5-A01'),/ปลายทาง/);
for(const file of ['app.js','model.js','site-map.js'])new vm.Script(fs.readFileSync('dist/'+file,'utf8'),{filename:file});
console.log('PASS: 150 unique kennels across buildings 1/2/3/4/6, cross-building moves retain history, clinic excluded, age, validation and syntax.');
